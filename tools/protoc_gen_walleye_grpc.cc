// protoc plugin generating walleye/photon gRPC stubs.
//
// Invoked by protoc as `--walleye-grpc_out=DIR`. For every service in the
// file it emits <proto>.grpc.pb.{h,cc} with:
//   - `<Service>Handler`: abstract server class (one virtual per method;
//     unary/server-streaming methods receive the parsed request, streaming
//     request sides are read via ReadMessage in the handler)
//   - `Register<Service>Service()`: wires the handler into a GrpcServer
//   - `<Service>Stub`: typed client over one GrpcClient connection.

#include <google/protobuf/compiler/code_generator.h>
#include <google/protobuf/compiler/plugin.h>
#include <google/protobuf/descriptor.h>
#include <google/protobuf/descriptor.pb.h>
#include <google/protobuf/io/coded_stream.h>
#include <google/protobuf/io/zero_copy_stream.h>

#include <memory>
#include <string>
#include <vector>

namespace {


std::string CppType(const google::protobuf::Descriptor* message) {
  // full_name() is dotted ("pkg.Outer.Inner"); C++ nesting uses "::".
  std::string out;
  for (char c : std::string(message->full_name())) {
    if (c == '.') {
      out += "::";
    } else {
      out += c;
    }
  }
  return out;
}

std::string MethodPath(const google::protobuf::ServiceDescriptor* service, const google::protobuf::MethodDescriptor* method) {
  return std::string("/") + std::string(service->full_name()) + "/" + std::string(method->name());
}

struct NamespaceScope {
  std::string open;
  std::string close;
};

NamespaceScope NamespacesFor(const std::string& package) {
  NamespaceScope scope;
  std::string indent;
  size_t start = 0;
  while (start <= package.size()) {
    size_t dot = package.find('.', start);
    std::string part = package.substr(start, dot == std::string::npos ? dot : dot - start);
    if (part.empty()) {
      break;
    }
    scope.open += "namespace " + part + " {\n";
    indent = part;  // last component kept for the closing comment
    scope.close = "}  // namespace " + part + "\n" + scope.close;
    if (dot == std::string::npos) {
      break;
    }
    start = dot + 1;
  }
  return scope;
}

class WalleyeGrpcGenerator : public google::protobuf::compiler::CodeGenerator {
 public:
  uint64_t GetSupportedFeatures() const override {
    return FEATURE_PROTO3_OPTIONAL;
  }

  bool Generate(const google::protobuf::FileDescriptor* file, const std::string& /*parameter*/,
                google::protobuf::compiler::GeneratorContext* context,
                std::string* /*error*/) const override {
    if (file->service_count() == 0) {
      return true;
    }
    std::string base(file->name());
    size_t slash = base.find_last_of('/');
    if (slash != std::string::npos) {
      base = base.substr(slash + 1);
    }
    base = base.substr(0, base.size() - 6);  // strip ".proto"

    NamespaceScope ns = NamespacesFor(std::string(file->package()));

    std::string header;
    header += "// Generated by protoc-gen-walleye-grpc. DO NOT EDIT.\n";
    header += std::string("// Source: ") + std::string(file->name()) + "\n#pragma once\n\n";
    header += "#include <string>\n\n";
    header += "#include \"absl/status/status.h\"\n";
    header += "#include \"absl/status/statusor.h\"\n\n";
    // Message headers first: protobuf pulls abseil logging whose macros
    // would collide with photon's if photon came first.
    header += "#include \"" + base + ".pb.h\"\n\n";
    header += "#include \"walleye/grpc/call.h\"\n";
    header += "#include \"walleye/grpc/server.h\"\n";
    header += "#include \"walleye/grpc/typed.h\"\n\n";
    header += ns.open + "\n";

    std::string source;
    source += "// Generated by protoc-gen-walleye-grpc. DO NOT EDIT.\n";
    source += std::string("// Source: ") + std::string(file->name()) + "\n";
    source += "#include \"" + base + ".grpc.pb.h\"\n\n";
    source += "#include <utility>\n\n";
    source += ns.open + "\n";

    for (int i = 0; i < file->service_count(); i++) {
      const google::protobuf::ServiceDescriptor* service = file->service(i);
      AppendService(service, &header, &source);
    }

    header += "\n" + ns.close;
    source += "\n" + ns.close;

    WriteFile(context, base + ".grpc.pb.h", header);
    WriteFile(context, base + ".grpc.pb.cc", source);
    return true;
  }

 private:
  static void WriteFile(google::protobuf::compiler::GeneratorContext* context, const std::string& name,
                        const std::string& content) {
    std::unique_ptr<google::protobuf::io::ZeroCopyOutputStream> output(context->Open(name));
    google::protobuf::io::CodedOutputStream coded(output.get());
    coded.WriteRaw(content.data(), static_cast<int>(content.size()));
  }

  static void AppendService(const google::protobuf::ServiceDescriptor* service, std::string* header, std::string* source) {
    const std::string svc(service->name());
    // -- handler base class --
    *header += "class " + svc + "Handler {\n";
    *header += " public:\n";
    *header += "  virtual ~" + svc + "Handler() = default;\n";
    for (int m = 0; m < service->method_count(); m++) {
      const google::protobuf::MethodDescriptor* method = service->method(m);
      const std::string in = CppType(method->input_type());
      const std::string out = CppType(method->output_type());
      const std::string mname(method->name());
      *header += "  // " + MethodSignatureComment(method) + "\n";
      if (!method->client_streaming() && !method->server_streaming()) {
        // Unary: the framework writes the response or the error status.
        *header += "  virtual absl::StatusOr<" + out + "> " + mname +
                   "(walleye::grpc::UnaryContext* ctx, const " + in + "& request) = 0;\n";
      } else if (!method->client_streaming()) {
        // Server-streaming: request pre-read; the stream only writes.
        *header += "  virtual void " + mname + "(walleye::grpc::ServerWriter<" + out +
                   ">* writer, const " + in + "& request) = 0;\n";
      } else if (!method->server_streaming()) {
        // Client-streaming: read-only stream; framework writes the reply.
        *header += "  virtual absl::StatusOr<" + out + "> " + mname + "(walleye::grpc::ServerReader<" +
                   in + ">* reader) = 0;\n";
      } else {
        *header += "  virtual void " + mname + "(walleye::grpc::ServerStream<" + in + ", " + out +
                   ">* stream) = 0;\n";
      }
    }
    *header += "};\n\n";
    *header += "void Register" + svc + "Service(walleye::grpc::GrpcServer* server, " + svc +
               "Handler* handler);\n\n";

    // -- stub class --
    *header += "class " + svc + "Stub {\n";
    *header += " public:\n";
    *header += "  explicit " + svc + "Stub(walleye::grpc::GrpcClient* client) : client_(client) {}\n\n";
    for (int m = 0; m < service->method_count(); m++) {
      const google::protobuf::MethodDescriptor* method = service->method(m);
      const std::string in = CppType(method->input_type());
      const std::string out = CppType(method->output_type());
      const std::string mname(method->name());
      const std::string typed = "absl::StatusOr<walleye::grpc::TypedCall<" + in + ", " + out + ">>";
      if (!method->client_streaming() && !method->server_streaming()) {
        *header += "  absl::StatusOr<" + out + "> " + mname + "(const " + in +
                   "& request, walleye::grpc::CallOptions options = {});\n";
      } else if (!method->client_streaming()) {
        *header += "  " + typed + " " + mname + "(const " + in +
                   "& request, walleye::grpc::CallOptions options = {});\n";
      } else {
        *header += "  " + typed + " " + mname + "(walleye::grpc::CallOptions options = {});\n";
      }
    }
    *header += "\n private:\n  walleye::grpc::GrpcClient* client_;\n};\n\n";

    // -- registration --
    *source += "void Register" + svc + "Service(walleye::grpc::GrpcServer* server, " + svc +
               "Handler* handler) {\n";
    for (int m = 0; m < service->method_count(); m++) {
      const google::protobuf::MethodDescriptor* method = service->method(m);
      const std::string in = CppType(method->input_type());
      const std::string out = CppType(method->output_type());
      const std::string mname(method->name());
      *source += "  server->Register(\"" + MethodPath(service, method) +
                 "\", [handler](walleye::grpc::ServerCall* call) {\n";
      if (!method->client_streaming() && !method->server_streaming()) {
        // Unary: framework reads the request, calls the handler, writes
        // the response or the mapped error status (+ response metadata).
        *source += "    absl::StatusOr<" + in + "> request = walleye::grpc::ReadOne<" + in + ">(call);\n";
        *source += "    if (!request.ok()) {\n";
        *source += "      walleye::grpc::FinishQuietly(call, walleye::grpc::StatusCode::kInternal,\n";
        *source += "                                 std::string(request.status().message()));\n";
        *source += "      return;\n    }\n";
        *source += "    walleye::grpc::UnaryContext ctx(call);\n";
        *source += "    absl::StatusOr<" + out + "> response = handler->" + mname + "(&ctx, *request);\n";
        *source += "    if (!response.ok()) {\n";
        *source += "      walleye::grpc::FinishQuietly(call, walleye::grpc::ToGrpcCode(response.status().code()),\n";
        *source += "                                 std::string(response.status().message()),\n";
        *source += "                                 ctx.TakeResponseMetadata());\n";
        *source += "      return;\n    }\n";
        *source += "    if (!walleye::grpc::WriteMessage(call, *response).ok()) {\n";
        *source += "      return;\n    }\n";
        *source += "    walleye::grpc::FinishQuietly(call, walleye::grpc::StatusCode::kOk, \"\",\n";
        *source += "                               ctx.TakeResponseMetadata());\n";
      } else if (!method->client_streaming()) {
        // Server-streaming: request pre-read, handler writes + closes.
        *source += "    absl::StatusOr<" + in + "> request = walleye::grpc::ReadOne<" + in + ">(call);\n";
        *source += "    if (!request.ok()) {\n";
        *source += "      walleye::grpc::FinishQuietly(call, walleye::grpc::StatusCode::kInternal,\n";
        *source += "                                 std::string(request.status().message()));\n";
        *source += "      return;\n    }\n";
        *source += "    walleye::grpc::ServerWriter<" + out + "> writer(call);\n";
        *source += "    handler->" + mname + "(&writer, *request);\n";
      } else if (!method->server_streaming()) {
        // Client-streaming: handler reads, returns the single response.
        *source += "    walleye::grpc::ServerReader<" + in + "> reader(call);\n";
        *source += "    absl::StatusOr<" + out + "> response = handler->" + mname + "(&reader);\n";
        *source += "    if (!response.ok()) {\n";
        *source += "      walleye::grpc::FinishQuietly(call, walleye::grpc::ToGrpcCode(response.status().code()),\n";
        *source += "                                 std::string(response.status().message()));\n";
        *source += "      return;\n    }\n";
        *source += "    if (!walleye::grpc::WriteMessage(call, *response).ok()) {\n";
        *source += "      return;\n    }\n";
        *source += "    walleye::grpc::FinishQuietly(call, walleye::grpc::StatusCode::kOk, \"\");\n";
      } else {
        // Bidi: handler owns both directions and closes.
        *source += "    walleye::grpc::ServerStream<" + in + ", " + out + "> stream(call);\n";
        *source += "    handler->" + mname + "(&stream);\n";
      }
      *source += "  });\n";
    }
    *source += "}\n\n";

    // -- stub methods --
    for (int m = 0; m < service->method_count(); m++) {
      const google::protobuf::MethodDescriptor* method = service->method(m);
      const std::string in = CppType(method->input_type());
      const std::string out = CppType(method->output_type());
      const std::string mname(method->name());
      const std::string typed = "absl::StatusOr<walleye::grpc::TypedCall<" + in + ", " + out + ">>";
      if (!method->client_streaming() && !method->server_streaming()) {
        *source += "absl::StatusOr<" + out + "> " + svc + "Stub::" + mname + "(const " + in +
                   "& request, walleye::grpc::CallOptions options) {\n";
        *source += "  return walleye::grpc::UnaryCall<" + in + ", " + out + ">(client_, \"" +
                   MethodPath(service, method) + "\", request, options);\n}\n\n";
      } else if (!method->client_streaming()) {
        *source += typed + " " + svc + "Stub::" + mname + "(const " + in +
                   "& request, walleye::grpc::CallOptions options) {\n";
        *source += "  return walleye::grpc::OpenStream<" + in + ", " + out + ">(client_, \"" +
                   MethodPath(service, method) + "\", options, &request);\n}\n\n";
      } else {
        *source += typed + " " + svc + "Stub::" + mname + "(walleye::grpc::CallOptions options) {\n";
        *source += "  return walleye::grpc::OpenStream<" + in + ", " + out + ">(client_, \"" +
                   MethodPath(service, method) + "\", options, nullptr);\n}\n\n";
      }
    }
  }

  static std::string MethodSignatureComment(const google::protobuf::MethodDescriptor* method) {
    std::string comment(method->input_type()->full_name());
    comment += method->client_streaming() ? " (stream)" : "";
    comment += " -> ";
    comment += std::string(method->output_type()->full_name());
    comment += method->server_streaming() ? " (stream)" : "";
    return comment;
  }
};

}  // namespace

int main(int argc, char** argv) {
  WalleyeGrpcGenerator generator;
  return google::protobuf::compiler::PluginMain(argc, argv, &generator);
}
